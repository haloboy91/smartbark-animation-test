#!/usr/bin/env python3
"""Emit web/js/poses.js from assets/elly/poses.json.

The web rig must never hardcode the pose list - it would drift the moment a pose
is added or renamed. This regenerates the JS-side index from the manifest, which
is the single source of truth.
"""
from __future__ import annotations

import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "assets", "elly", "poses.json")
OUT = os.path.join(ROOT, "web", "js", "poses.js")


def main() -> None:
    with open(SRC, encoding="utf-8") as fh:
        m = json.load(fh)

    rows = []
    for p in m["poses"]:
        if not p.get("available"):
            continue
        path = f"assets/elly/cutouts/{p['file']}.png"
        if not os.path.exists(os.path.join(ROOT, path)):
            print(f"  skip {p['id']}: no file at {path}")
            continue
        rows.append((p["id"], path, p["source"]))

    lines = [
        "// GENERATED by tools/build_web_assets.py from assets/elly/poses.json.",
        "// Do not edit by hand - run: python3 tools/build_web_assets.py",
        "",
        "export const POSES = {",
    ]
    for pid, path, src in rows:
        lines.append(f"  {pid}: '{path}',")
    lines.append("};")
    lines.append("")
    lines.append(f"export const POSE_IDS = {sorted(r[0] for r in rows)!r};".replace("'", '"'))
    lines.append("")

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))

    print(f"{len(rows)} poses -> {os.path.relpath(OUT, ROOT)}")


if __name__ == "__main__":
    main()
