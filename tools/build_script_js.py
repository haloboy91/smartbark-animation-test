#!/usr/bin/env python3
"""docs/script.txt -> web/js/script.js

Keeps the kit's convention: parts separated by `###`, first line is the title.
Card text comes from the storyboard's ON-SCREEN CHAPTER CARD field where
present, so the overlay matches the brief.
"""
from __future__ import annotations

import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "docs", "script.txt")
BRIEF = os.path.join(ROOT, "docs", "EP015_storyboard_brief.txt")
OUT = os.path.join(ROOT, "web", "js", "script.js")

FALLBACK_CARDS = [
    "PART 0: THE CRASH THAT MADE SOME MEN RICH",
    "CHAPTER 1: WHEN EVERYONE THOUGHT THEY WERE A GENIUS",
    "CHAPTER 2: THE PARTY ENDS",
    "CHAPTER 3: THE MAN WHO BET AGAINST AMERICA",
    "CHAPTER 4: THE MAN WHO LEFT THE PARTY EARLY",
    "CHAPTER 5: WHEN CASH BECOMES POWER",
    "CHAPTER 6: THE MAN WHO COULDN'T KEEP HIS FORTUNE",
    "CHAPTER 7: THE REAL SECRET",
]


def cards_from_brief() -> list[str]:
    """Pull the ON-SCREEN CHAPTER CARD text for each part, in order."""
    if not os.path.exists(BRIEF):
        return FALLBACK_CARDS
    found = []
    for line in open(BRIEF, encoding="utf-8"):
        m = re.match(r"ON-SCREEN CHAPTER CARD:\s*(.+?)\s*\[", line)
        if m:
            found.append(m.group(1).strip())
    return found[:8] if len(found) >= 8 else FALLBACK_CARDS


def main() -> None:
    raw = open(SRC, encoding="utf-8").read()
    blocks = [b.strip() for b in raw.split("###")]
    title = blocks[0].strip()
    parts = [b for b in blocks[1:] if b]
    cards = cards_from_brief()

    if len(parts) != 8:
        raise SystemExit(f"expected 8 parts in script.txt, found {len(parts)}")

    out = [
        "// GENERATED by tools/build_script_js.py from docs/script.txt.",
        "// Do not edit by hand.",
        "//",
        "// EP015 narration, verbatim from the approved script.",
        "//",
        "// TIMING NOTE: the real episode times cuts from word-level ASR alignment",
        "// of the eight VO WAVs (kit v2: asr.py -> align.py -> cues.py). Those WAVs",
        "// are not in this repo, so the engine derives SYNTHETIC word timings from a",
        "// speaking rate. Every timing here is provisional and is replaced wholesale",
        "// by real words.json when the VO lands.",
        "",
        "// tuned so synthetic part lengths land near the storyboard's WAV durations",
        "export const WPM = 155;",
        "",
        f"export const TITLE = {json.dumps(title)};",
        "",
        "export const PARTS = [",
    ]
    for i, (text, card) in enumerate(zip(parts, cards)):
        one_line = re.sub(r"\s+", " ", text).strip()
        out.append("  {")
        out.append(f"    id: 'p{i}',")
        out.append(f"    card: {json.dumps(card)},")
        out.append(f"    text: {json.dumps(one_line)},")
        out.append("  },")
    out.append("];")

    out.append("""
// Build word timings. The real pipeline replaces this with words.json from align.py.
export function buildWords(part, wpm = WPM) {
  const tokens = part.text.trim().split(/\\s+/);
  const secPerWord = 60 / wpm;
  let t = 0;
  return tokens.map((w) => {
    let dur = secPerWord * (0.6 + 0.4 * Math.min(w.length / 5, 1.6));
    if (/[.!?]$/.test(w)) dur += 0.34;
    else if (/[,;:]$/.test(w)) dur += 0.16;
    const word = { w, t0: t, t1: t + dur };
    t += dur + secPerWord * 0.12;
    return word;
  });
}""")

    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")

    wc = sum(len(p.split()) for p in parts)
    print(f"{len(parts)} parts, {wc} words -> {os.path.relpath(OUT, ROOT)}")
    for i, c in enumerate(cards):
        print(f"  p{i}: {c}")


if __name__ == "__main__":
    main()
